//! `codemosis.lock`: the exact packs a project was reviewed against.
//!
//! A pack is a set of claims ("this correction is safe when..."), so a
//! change to a pack is a change to what the engine will do to the code.
//! When a project has a lockfile, a pack whose content no longer matches its
//! pinned SHA-256 does not load until someone reviews the change and runs
//! `codemosis lock` again. This holds for built-in packs too: upgrading the
//! engine is a reviewed change, not a silent one.

use codemosis_core::Pack;
use serde::{Deserialize, Serialize};
use std::path::Path;

pub const LOCK_FILE: &str = "codemosis.lock";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Lock {
    pub version: u32,
    /// The engine that wrote the lock (informational).
    pub engine: String,
    #[serde(default, rename = "pack")]
    pub packs: Vec<LockedPack>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct LockedPack {
    pub id: String,
    pub version: String,
    /// `builtin` or the pack's directory as configured.
    pub source: String,
    pub sha256: String,
}

fn source_of(p: &Pack) -> String {
    if p.origin.starts_with("builtin:") {
        "builtin".to_string()
    } else {
        p.origin.clone()
    }
}

impl Lock {
    pub fn of(packs: &[Pack]) -> Lock {
        let mut locked: Vec<LockedPack> = packs
            .iter()
            .map(|p| LockedPack {
                id: p.meta.id.clone(),
                version: p.meta.version.clone(),
                source: source_of(p),
                sha256: p.digest.clone(),
            })
            .collect();
        locked.sort_by(|a, b| a.id.cmp(&b.id));
        Lock {
            version: 1,
            engine: codemosis_core::version::ENGINE_VERSION.to_string(),
            packs: locked,
        }
    }

    pub fn load(root: &Path) -> Result<Option<Lock>, String> {
        let path = root.join(LOCK_FILE);
        if !path.is_file() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(&path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        let lock: Lock = toml::from_str(&text).map_err(|e| format!("{LOCK_FILE} is not valid: {e}"))?;
        if lock.version != 1 {
            return Err(format!(
                "{LOCK_FILE} has version {}; this engine reads version 1",
                lock.version
            ));
        }
        Ok(Some(lock))
    }

    pub fn to_toml(&self) -> String {
        format!(
            "# The packs this project was reviewed against, pinned by content.\n\
             # Generated by `codemosis lock`; review pack changes, then run it again.\n\n{}",
            toml::to_string_pretty(self).expect("serializable")
        )
    }

    /// Every way the loaded packs differ from the lock.
    pub fn verify(&self, packs: &[Pack]) -> Vec<String> {
        let ids: Vec<(String, String, String)> = packs
            .iter()
            .map(|p| (p.meta.id.clone(), p.meta.version.clone(), p.digest.clone()))
            .collect();
        self.verify_ids(&ids)
    }

    /// Every way these packs, as (id, version, sha256), differ from the lock.
    pub fn verify_ids(&self, packs: &[(String, String, String)]) -> Vec<String> {
        let mut problems = Vec::new();
        for (id, version, digest) in packs {
            match self.packs.iter().find(|l| l.id == *id) {
                None => problems.push(format!("pack '{id}' is loaded but not pinned in {LOCK_FILE}")),
                Some(l) if l.sha256 != *digest => problems.push(format!(
                    "pack '{id}' changed since it was pinned (version {} -> {version}, sha256 {}… -> {}…)",
                    l.version,
                    &l.sha256[..12.min(l.sha256.len())],
                    &digest[..12.min(digest.len())]
                )),
                Some(_) => {}
            }
        }
        for l in &self.packs {
            if !packs.iter().any(|(id, _, _)| *id == l.id) {
                problems.push(format!("{LOCK_FILE} pins pack '{}', which is no longer loaded", l.id));
            }
        }
        problems
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip_and_verify() {
        let packs = codemosis_core::pack::builtin().unwrap();
        let lock = Lock::of(&packs);
        let back: Lock = toml::from_str(&lock.to_toml()).unwrap();
        assert_eq!(back, lock);
        assert!(lock.verify(&packs).is_empty());
        let mut tampered = lock.clone();
        tampered.packs[0].sha256 = "0".repeat(64);
        let problems = tampered.verify(&packs);
        assert_eq!(problems.len(), 1);
        assert!(problems[0].contains("changed since it was pinned"), "{problems:?}");
        assert!(Lock::of(&packs[1..]).verify(&packs)[0].contains("not pinned"));
    }
}
